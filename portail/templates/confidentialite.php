    <h1>Données personnelles</h1>
    <p class="article__chapo">PixelWave Studio ne collecte que les données nécessaires au fonctionnement du portail (principe de minimisation du RGPD).</p>

    <table class="tableau">
        <thead><tr><th>Donnée</th><th>Pourquoi</th><th>Durée de conservation</th></tr></thead>
        <tbody>
            <tr><td>Pseudo, e-mail</td><td>Identifier ton compte, te contacter au sujet d'un ticket</td><td>Tant que le compte existe</td></tr>
            <tr><td>Mot de passe</td><td>Connexion (stocké haché, jamais en clair)</td><td>Tant que le compte existe</td></tr>
            <tr><td>Commandes et clés</td><td>Accès aux jeux achetés, obligations comptables</td><td>10 ans (obligation légale)</td></tr>
            <tr><td>Tickets et messages</td><td>Suivi des bugs et du support</td><td>3 ans après clôture</td></tr>
            <tr><td>Adresse IP des connexions</td><td>Protection contre les tentatives d'intrusion</td><td>30 jours</td></tr>
            <tr><td>Abonnement newsletter</td><td>Envoi des actualités, uniquement si tu l'as accepté</td><td>Jusqu'à désinscription</td></tr>
        </tbody>
    </table>

    <p>Aucune donnée bancaire n'est stockée par le portail. Tu peux demander l'accès, la rectification ou la suppression de tes données en écrivant à <a class="lien" href="mailto:dpo@pixelwave.test">dpo@pixelwave.test</a>.</p>
