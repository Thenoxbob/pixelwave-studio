    <h1>Aide du portail joueurs</h1>
    <p class="article__chapo">Les réponses aux questions les plus fréquentes. Tu ne trouves pas ? <a class="lien" href="/support/nouveau">Écris au support</a>.</p>

    <h2>Acheter un jeu ou un DLC</h2>
    <ol>
        <li>Dans la <a class="lien" href="/boutique">boutique</a>, ouvre la fiche du produit.</li>
        <li>Choisis ta plateforme (PC, PS5, Switch) puis clique sur « Ajouter au panier ».</li>
        <li>Dans le panier, clique sur « Payer et recevoir mes clés ».</li>
    </ol>
    <p>Une plateforme grisée signifie que le produit est en rupture de clés ou que tu le possèdes déjà.</p>

    <h2>Récupérer et utiliser une clé d'activation</h2>
    <ol>
        <li>Va dans <a class="lien" href="/bibliotheque">Ma bibliothèque</a>.</li>
        <li>Clique sur « Afficher la clé » puis sur « Copier ».</li>
        <li>Colle la clé dans le store de ta plateforme (Steam, PlayStation Store, Nintendo eShop).</li>
    </ol>
    <p>Pour ta sécurité, la clé reste masquée tant que tu ne demandes pas à l'afficher.</p>

    <h2>Signaler un bug et suivre sa correction</h2>
    <p>Depuis <a class="lien" href="/support/nouveau">Signaler un bug</a>, indique le jeu, la plateforme, la version et décris ce qui se passe. Tu reçois une référence (ex. BUG-2026-0007) et tu suis l'avancement dans <a class="lien" href="/support">Support</a> :</p>
    <ul>
        <li><strong>Nouveau</strong> : l'équipe n'a pas encore lu ton signalement.</li>
        <li><strong>En cours</strong> : un membre de l'équipe QA s'en occupe.</li>
        <li><strong>En attente du joueur</strong> : on a besoin d'une précision, réponds dans le ticket.</li>
        <li><strong>Résolu</strong> : un correctif est disponible.</li>
        <li><strong>Clos</strong> : le ticket est terminé.</li>
    </ul>

    <h2>Sécurité de ton compte</h2>
    <p>L'équipe PixelWave ne te demandera jamais ton mot de passe. Après plusieurs essais de connexion ratés, le compte est bloqué 15 minutes pour le protéger.</p>

    <h2 id="cgv">Conditions générales de vente (résumé)</h2>
    <p>Les prix sont indiqués TTC. Une clé révélée est considérée comme utilisée et n'est plus remboursable. Une clé non révélée peut être remboursée dans les 14 jours via le support.</p>
